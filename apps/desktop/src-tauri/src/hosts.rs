//! The hosts the user added, as JSON in the app data directory, and their
//! private keys in the OS key store (never in the JSON).

use std::path::PathBuf;

use herdr_session::SpaceSort;
use serde::{Deserialize, Serialize};

use crate::error::AppError;

/// Same service name as the Keychain items of the Apple apps.
const KEY_SERVICE: &str = "net.staude.amiscara.agents.ssh-key";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum HostKind {
    /// The Unix socket on this machine (Linux, and the Mac in development).
    Local,
    /// A remote server over SSH.
    Ssh,
}

/// How an SSH host logs in.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Auth {
    /// A key of its own, generated by the app, in the OS key store.
    #[default]
    Key,
    /// The SSH agent (Windows OpenSSH agent, `SSH_AUTH_SOCK` on Linux).
    Agent,
}

/// One host; the fields follow `HostConfig` of the Apple apps.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HostConfig {
    pub id: String,
    pub name: String,
    pub kind: HostKind,
    #[serde(default)]
    pub host: String,
    #[serde(default = "default_port")]
    pub port: u16,
    #[serde(default)]
    pub user: String,
    /// Path of `herdr.sock` on the server; for a local host empty means
    /// `~/.config/herdr/herdr.sock`.
    #[serde(default)]
    pub socket_path: String,
    /// Trusted host key as an OpenSSH public key line, set once the user
    /// confirmed the fingerprint.
    #[serde(default)]
    pub pinned_host_key: Option<String>,
    /// Public half of this device's key, for `authorized_keys`.
    #[serde(default)]
    pub public_key: Option<String>,
    #[serde(default)]
    pub auth: Auth,
    /// Whether the app may send prompts and keys; missing means on.
    #[serde(default)]
    pub allow_input: Option<bool>,
    /// Whether files may be uploaded over SFTP; missing means off.
    #[serde(default)]
    pub allow_upload: Option<bool>,
    /// Whether the key's line lets pages on the host's `localhost` through
    /// (#247); missing means off.
    #[serde(default)]
    pub allow_web_forward: Option<bool>,
    /// Notifications when an agent waits or finishes; missing means on.
    #[serde(default)]
    pub notify: Option<bool>,
    /// Grouping of "Bereich/Name" spaces; missing means on.
    #[serde(default)]
    pub group_spaces: Option<bool>,
    /// Order of spaces in the sidebar; missing means herdr's.
    #[serde(default)]
    pub space_sort: Option<SpaceSortMode>,
    /// Workspace IDs in the user's order, for `SpaceSortMode::Manual`.
    #[serde(default)]
    pub space_order: Option<Vec<String>>,
}

/// The order of spaces in the sidebar; same values as in the Apple apps.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum SpaceSortMode {
    Herdr,
    NameAscending,
    NameDescending,
    Manual,
}

fn default_port() -> u16 {
    22
}

impl HostConfig {
    pub fn group_spaces_by_name(&self) -> bool {
        self.group_spaces.unwrap_or(true)
    }

    /// What the session sorts spaces by.
    pub fn space_sort(&self) -> SpaceSort {
        match self.space_sort.unwrap_or(SpaceSortMode::Herdr) {
            SpaceSortMode::Herdr => SpaceSort::Herdr,
            SpaceSortMode::NameAscending => SpaceSort::NameAscending,
            SpaceSortMode::NameDescending => SpaceSort::NameDescending,
            SpaceSortMode::Manual => {
                SpaceSort::Manual(self.space_order.clone().unwrap_or_default())
            }
        }
    }

    /// The `socket_path` for an `authorized_keys` line: `None` for the
    /// default below the login's home directory, which the line reaches
    /// through `$HOME`.
    pub fn custom_socket(&self) -> Option<&str> {
        let path = self.socket_path.trim();
        (!path.is_empty() && !path.ends_with("/.config/herdr/herdr.sock")).then_some(path)
    }
}

/// The hosts, in the order the user sees them.
pub struct HostStore {
    path: PathBuf,
    hosts: Vec<HostConfig>,
}

impl HostStore {
    /// Loads `hosts.json` from `dir`; a missing file is an empty list.
    pub fn load(dir: PathBuf) -> Result<Self, AppError> {
        let path = dir.join("hosts.json");
        let hosts = match std::fs::read(&path) {
            Ok(data) => serde_json::from_slice(&data)
                .map_err(|err| AppError::Store(format!("{}: {err}", path.display())))?,
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => Vec::new(),
            Err(err) => return Err(AppError::Store(format!("{}: {err}", path.display()))),
        };
        Ok(Self { path, hosts })
    }

    pub fn hosts(&self) -> &[HostConfig] {
        &self.hosts
    }

    pub fn get(&self, id: &str) -> Result<HostConfig, AppError> {
        self.hosts
            .iter()
            .find(|host| host.id == id)
            .cloned()
            .ok_or_else(|| AppError::NoHost(id.to_owned()))
    }

    /// Adds `host` or replaces the one with its id, then writes the file.
    pub fn put(&mut self, host: HostConfig) -> Result<(), AppError> {
        match self.hosts.iter_mut().find(|known| known.id == host.id) {
            Some(known) => *known = host,
            None => self.hosts.push(host),
        }
        self.save()
    }

    pub fn remove(&mut self, id: &str) -> Result<(), AppError> {
        self.hosts.retain(|host| host.id != id);
        self.save()
    }

    /// Writes to a temporary file first, so a crash never leaves half a list.
    fn save(&self) -> Result<(), AppError> {
        let error = |err: &dyn std::fmt::Display| {
            AppError::Store(format!("{}: {err}", self.path.display()))
        };
        if let Some(dir) = self.path.parent() {
            std::fs::create_dir_all(dir).map_err(|err| error(&err))?;
        }
        let data = serde_json::to_vec_pretty(&self.hosts).map_err(|err| error(&err))?;
        let tmp = self.path.with_extension("json.tmp");
        std::fs::write(&tmp, data).map_err(|err| error(&err))?;
        std::fs::rename(&tmp, &self.path).map_err(|err| error(&err))
    }
}

/// Saved prompts for the input bar, per device, as `quick-replies.json`.
pub struct QuickReplies {
    path: PathBuf,
    /// `None` until the user saves a list: the defaults in the current language.
    replies: Option<Vec<String>>,
}

impl QuickReplies {
    pub fn load(dir: PathBuf) -> Self {
        let path = dir.join("quick-replies.json");
        let replies = std::fs::read(&path)
            .ok()
            .and_then(|data| serde_json::from_slice(&data).ok());
        Self { path, replies }
    }

    /// The saved list, or the defaults as in the Apple apps.
    pub fn list(&self) -> Vec<String> {
        self.replies
            .clone()
            .unwrap_or_else(crate::i18n::default_quick_replies)
    }

    /// Keeps the entries that are not blank, trimmed, and writes the file.
    pub fn set(&mut self, replies: Vec<String>) -> Result<(), AppError> {
        let replies: Vec<String> = replies
            .into_iter()
            .map(|reply| reply.trim().to_owned())
            .filter(|reply| !reply.is_empty())
            .collect();
        let error = |err: &dyn std::fmt::Display| {
            AppError::Store(format!("{}: {err}", self.path.display()))
        };
        if let Some(dir) = self.path.parent() {
            std::fs::create_dir_all(dir).map_err(|err| error(&err))?;
        }
        let data = serde_json::to_vec_pretty(&replies).map_err(|err| error(&err))?;
        std::fs::write(&self.path, data).map_err(|err| error(&err))?;
        self.replies = Some(replies);
        Ok(())
    }
}

/// The private key of a host, from the OS key store.
pub fn private_key(host_id: &str) -> Result<Option<String>, AppError> {
    match keyring::Entry::new(KEY_SERVICE, host_id)?.get_password() {
        Ok(key) => Ok(Some(key)),
        Err(keyring::Error::NoEntry) => Ok(None),
        Err(err) => Err(err.into()),
    }
}

pub fn store_private_key(host_id: &str, key: &str) -> Result<(), AppError> {
    Ok(keyring::Entry::new(KEY_SERVICE, host_id)?.set_password(key)?)
}

pub fn delete_private_key(host_id: &str) -> Result<(), AppError> {
    match keyring::Entry::new(KEY_SERVICE, host_id)?.delete_credential() {
        Ok(()) | Err(keyring::Error::NoEntry) => Ok(()),
        Err(err) => Err(err.into()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn old_and_sparse_hosts_load_with_defaults() {
        let json = r#"[{"id":"a","name":"work","kind":"ssh","host":"work","user":"frank"}]"#;
        let hosts: Vec<HostConfig> = serde_json::from_str(json).expect("hosts");
        let host = &hosts[0];
        assert_eq!(host.port, 22);
        assert_eq!(host.auth, Auth::Key);
        assert!(host.group_spaces_by_name());
        assert!(host.pinned_host_key.is_none());
        assert_eq!(host.space_sort(), SpaceSort::Herdr);
    }

    #[test]
    fn space_sort_uses_the_manual_order() {
        let host: HostConfig = serde_json::from_str(
            r#"{"id":"a","name":"w","kind":"local","spaceSort":"manual","spaceOrder":["w2","w1"]}"#,
        )
        .expect("host");
        assert_eq!(
            host.space_sort(),
            SpaceSort::Manual(vec!["w2".into(), "w1".into()])
        );
        let host: HostConfig = serde_json::from_str(
            r#"{"id":"a","name":"w","kind":"local","spaceSort":"nameDescending"}"#,
        )
        .expect("host");
        assert_eq!(host.space_sort(), SpaceSort::NameDescending);
    }

    #[test]
    fn default_sockets_go_through_home() {
        let mut host: HostConfig = serde_json::from_str(
            r#"{"id":"a","name":"w","kind":"ssh","socketPath":"/Users/frank/.config/herdr/herdr.sock"}"#,
        )
        .expect("host");
        assert_eq!(host.custom_socket(), None);
        host.socket_path = "/srv/herdr.sock".into();
        assert_eq!(host.custom_socket(), Some("/srv/herdr.sock"));
    }

    #[test]
    fn the_store_round_trips() {
        let dir = std::env::temp_dir().join(format!("amiscara-hosts-{}", uuid::Uuid::new_v4()));
        let mut store = HostStore::load(dir.clone()).expect("empty");
        assert!(store.hosts().is_empty());
        let host: HostConfig =
            serde_json::from_str(r#"{"id":"a","name":"w","kind":"local"}"#).expect("host");
        store.put(host).expect("put");
        let again = HostStore::load(dir.clone()).expect("load");
        assert_eq!(again.get("a").expect("a").name, "w");
        std::fs::remove_dir_all(dir).ok();
    }
}
